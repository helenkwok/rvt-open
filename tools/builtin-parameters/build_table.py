#!/usr/bin/env python3
"""Write src/builtin_parameters/table.rs from public sources only.

usage: build_table.py INPUTS_DIR OUT.rs

INPUTS_DIR (tools/builtin-parameters/inputs/):
  bip_enum.tsv     name, value, label of every member of the Revit 2027 API reference's BuiltInParameter page
  bic_enum.tsv     name, value of every BuiltInCategory member of the same reference
  storage.tsv      id, type, models, counts: the type of the values public files store (derive_storage.py)
  group-spec.tsv   id, group, IFC value type, route: Revit's own IFC export of public samples (derive_ifc.py)
  enum-texts.tsv   id, value, text: the same export, integer parameters it writes as text
  help-terms.tsv   id, language, term, topic: one consistent help term in each of the 12 languages (derive_help.py)
  category-names.tsv  id, name, votes, models, other names: Revit's IFC export of public samples (derive_categories.py)
The Revit API dump of public samples is not an input: it is the answer key `score.py` checks the result against."""
import hashlib, os, sys

d, out = sys.argv[1:3]
# Ids Helen decided to keep with an empty name: no public source names them (the reference lacks them).
KEPT_NO_NAME = [-1154658, -1154657, -1140313, -1017024, -1017023, -1006800, -1005051]
SPEC = {
    'IFCLENGTHMEASURE': 'autodesk.spec.aec:length-2.0.0',
    'IFCAREAMEASURE': 'autodesk.spec.aec:area-2.0.0',
    'IFCVOLUMEMEASURE': 'autodesk.spec.aec:volume-2.0.0',
    'IFCPLANEANGLEMEASURE': 'autodesk.spec.aec:angle-2.0.0',
    'IFCBOOLEAN': 'autodesk.spec:spec.bool-1.0.0',
    'IFCINTEGER': 'autodesk.spec:spec.int64-2.0.0',
    'IFCREAL': 'autodesk.spec.aec:number-2.0.0',
    'IFCELECTRICCURRENTMEASURE': 'autodesk.spec.aec.electrical:current-2.0.0',
    'IFCELECTRICVOLTAGEMEASURE': 'autodesk.spec.aec.electrical:potential-2.0.0',
    'IFCPOWERMEASURE': 'autodesk.spec.aec.electrical:power-2.0.0',
    'IFCVOLUMETRICFLOWRATEMEASURE': 'autodesk.spec.aec.hvac:airFlow-2.0.0',
    'IFCPRESSUREMEASURE': 'autodesk.spec.aec.hvac:pressure-2.0.0',
}
LANGS = ['CHT', 'CHS', 'CSY', 'DEU', 'ESP', 'FRA', 'ITA', 'JPN', 'KOR', 'PLK', 'PTB', 'RUS']


def rows(name):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        return []
    with open(p, encoding='utf-8') as f:
        return [l.rstrip('\n').split('\t') for l in f if not l.startswith('#') and l.strip()]


def sha(name):
    return hashlib.sha256(open(os.path.join(d, name), 'rb').read()).hexdigest()[:16]


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


bip = {}
for r in rows('bip_enum.tsv'):
    bip.setdefault(int(r[1]), (r[0], r[2] if len(r) > 2 else ''))
bic = {}
for r in rows('bic_enum.tsv'):
    bic.setdefault(int(r[1]), r[0])
storage = {int(r[0]): r[1] for r in rows('storage.tsv')}
gs = {int(r[0]): (r[1], r[2]) for r in rows('group-spec.tsv')}
help_ = {}
for r in rows('help-terms.tsv'):
    help_.setdefault(int(r[0]), {})[r[1]] = (r[2], r[3])
ids = sorted({i for i in bip if i < -1} | set(KEPT_NO_NAME))
params = []
for i in ids:
    enum, label = bip.get(i, ('', ''))
    group, ity = gs.get(i, ('', ''))
    spec = SPEC.get(ity, '')
    st = storage.get(i, '')
    labels = help_.get(i)
    src = ''.join([
        'R' if label else '-', 'R' if enum else '-', 'F' if st else '-',
        'E' if spec else '-', 'E' if group else '-', 'H' if labels else '-'])
    params.append((i, label, enum, st, spec, group, src))
enum_texts = sorted((int(r[0]), int(r[1]), r[2]) for r in rows('enum-texts.tsv') if r[1].lstrip('-').isdigit())
catnames = {int(r[0]): r[1] for r in rows('category-names.tsv')}
cats = sorted((c, bic[c], catnames.get(c, '')) for c in bic if c < 0)
with open(out, 'w', encoding='utf-8') as f:
    f.write(f"""// @generated by tools/builtin-parameters/build_table.py from tools/builtin-parameters/inputs/; do not edit.
// Public sources only. The source column of each entry has one code per field, in this order: name,
// enum name, storage type, spec, group, localized names. R = the Revit 2027 API reference
// (BuiltInParameter and BuiltInCategory pages, help.autodesk.com), F = the type of the values public
// sample files store (the element's own value sets and its other parameter sets), E = Revit's own IFC
// export of public samples (the property set and value type of the property of the same name),
// H = machine-matched: the term at the same place of the same Revit 2027 help topic in each of the 12
// languages, cited per entry; - = no public source, the field is empty.
//  - inputs: bip_enum.tsv {sha('bip_enum.tsv')}, bic_enum.tsv {sha('bic_enum.tsv')}, storage.tsv {sha('storage.tsv')},
//    group-spec.tsv {sha('group-spec.tsv')}, enum-texts.tsv {sha('enum-texts.tsv')}, help-terms.tsv {sha('help-terms.tsv') if os.path.exists(os.path.join(d, 'help-terms.tsv')) else 'none'}.
//  - ids: the reference's BuiltInParameter members plus {len(KEPT_NO_NAME)} ids kept with no name (no public source names them).
//  - category names: the `Category` property of Revit's IFC export of public samples, the most voted name of each category id (category-names.tsv {sha('category-names.tsv')}); where it has none, the help term of `program_names`.
//  - The Revit API dump of the public samples is the answer key only: tools/builtin-parameters/score.py.

/// (id, name, BuiltInParameter enum name, storage type, spec type id, group label, source codes), by id.
pub(super) const PARAMETERS: &[(i64, &str, &str, &str, &str, &str, &str)] = &[
""")
    for p in params:
        f.write(f"    ({p[0]}, {q(p[1])}, {q(p[2])}, {q(p[3])}, {q(p[4])}, {q(p[5])}, {q(p[6])}),\n")
    f.write("];\n\n/// (parameter id, integer value, text) of enumerations, by id then value.\npub(super) const ENUM_TEXTS: &[(i64, i64, &str)] = &[\n")
    for e in enum_texts:
        f.write(f"    ({e[0]}, {e[1]}, {q(e[2])}),\n")
    f.write("];\n\n/// (BuiltInCategory id, enum name from the API reference, name from the IFC export), by id.\npub(super) const CATEGORIES: &[(i64, &str, &str)] = &[\n")
    for c in cats:
        f.write(f"    ({c[0]}, {q(c[1])}, {q(c[2])}),\n")
    f.write("];\n\n/// (parameter id, (term, help topic) in CHT CHS CSY DEU ESP FRA ITA JPN KOR PLK PTB RUS), by id.\npub(super) const LOCALIZED: &[(i64, [(&str, &str); 12])] = &[\n")
    for i in sorted(help_):
        if i in set(ids):
            cells = ', '.join(f"({q(help_[i].get(l, ('', ''))[0])}, {q(help_[i].get(l, ('', ''))[1])})" for l in LANGS)
            f.write(f"    ({i}, [{cells}]),\n")
    f.write("];\n")
print(len(params), len(enum_texts), len(cats), len(help_))
