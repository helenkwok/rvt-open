def field(root, name):
    for n, v in root["fields"]:
        if n == name:
            return v
    return None


def fid(root, name):
    v = field(root, name)
    return v.get("id") if isinstance(v, dict) and "id" in v else None


def section_of(facts, parts):
    """Section index of every element object, by the member its header lies in."""
    out = {}
    for name, (ms, secs) in parts.items():
        starts, at = [], 0
        for _, _, body in ms:
            starts.append(at)
            at += len(body)
        import bisect
        for e in facts["elements"]:
            if e["stream"] == name:
                k = bisect.bisect_right(starts, e["offset"]) - 1
                out[e["id"]] = secs[k]
    return out


# The schema class element types derive from: all 901 elements the API dump marks as types do,
# and 169 more whose API class is ElementType although the dump marks them as no type.
TYPE_BASES = {"Symbol"}

HOST_FIELDS = ("m_hostId",)

ATTRS = ("class", "category", "is_type", "name", "level", "host", "workset", "phase_created",
         "phase_demolished", "design_option", "unique_id")


def compare_elements(api, facts, sections, cls):
    by_id = {}
    for e in facts["elements"]:
        by_id.setdefault(e["id"], e)
    header = {h["id"]: h["root"] for h in facts.get("headers", []) if h.get("root")}
    # ElemRec.m_partitionId: u32 at +36 of a 40-byte element table row (Revit 2024 and later).
    partition = {r[1]: int.from_bytes(bytes.fromhex(r[5])[36:40], "little")
                 for r in facts["elem_table"] if len(r) > 5 and r[4] == 40}
    rows_et = {r[1] for r in facts["elem_table"]} | {r[2] for r in facts["elem_table"]}
    # Class: the file's class decodes the API's when the pairs seen form a function.
    pairs = collections.defaultdict(set)
    for a in api:
        e = by_id.get(a["id"])
        if e:
            pairs[cls[e["tag"]]].add(a["class"].split(".")[-1])
    bases = {int(k): v for k, v in facts.get("bases", {}).items()}

    def is_type(tag):
        # An element type's class derives from one of TYPE_BASES in the file's own schema.
        seen = 0
        while tag is not None and seen < 64:
            if cls.get(tag) in TYPE_BASES:
                return True
            tag, seen = bases.get(tag), seen + 1
        return False

    rows, status = [], collections.Counter()
    for a in api:
        e = by_id.get(a["id"])
        r = {"id": a["id"], "api_class": a["class"].split(".")[-1], "located": "yes" if e and a["id"] in rows_et else "no"}
        if not e:
            for k in ATTRS:
                r[k] = "not located"
            rows.append(r)
            continue
        root = e["root"]
        fc = cls[e["tag"]]
        r["file_class"] = fc
        r["class"] = "match" if len(pairs[fc]) == 1 else "ambiguous"

        def cmp(k, got, want, norm=lambda x: x):
            r[k] = "not decoded" if got is None else ("match" if norm(got) == norm(want) else "differ")

        h = header.get(a["id"])
        # The element header's category (the schema spells it m_categroryId).
        cmp("category", fid(h, "m_categroryId") if h else None, a.get("category_id"), lambda x: -1 if x is None else x)
        cmp("is_type", is_type(e["tag"]) if bases else None, a.get("is_type"))
        cmp("name", field(root, "m_name"), a.get("name"))
        cmp("level", fid(root, "m_assocLevelId"), a.get("level_id"), lambda x: -1 if x is None else x)
        # The host is the element's own host-id field; a class with none has no host. Not tested
        # on a hosted element: none of this file's 5,601 elements has a host in the API dump.
        host = next((fid(root, n) for n in HOST_FIELDS if field(root, n) is not None), -1)
        cmp("host", host, a.get("host_id"), lambda x: -1 if x is None else x)
        cmp("workset", partition.get(a["id"]), a.get("workset_id"))
        cmp("phase_created", fid(root, "m_createdPhaseId"), a.get("phase_created"))
        cmp("phase_demolished", fid(root, "m_demolishedPhaseId"), a.get("phase_demolished"))
        # -1 and -4 both read as no design option in the API (-4 on 2,232 of 2,232 here).
        cmp("design_option", fid(root, "m_designOptionId"), a.get("design_option"), lambda x: -1 if x in (None, -4) else x)
        cmp("unique_id", facts.get("unique_ids", {}).get(str(a["id"])), a.get("unique_id"))
        rows.append(r)
    api_ids = {a["id"] for a in api}
    extra = collections.Counter()
    for e in facts["elements"]:
        if e["id"] in api_ids:
            continue
        sec = sections.get(e["id"], 0)
        extra["embedded content document (section >= 1)" if sec >= 1 else "host document (section 0), not an API element"] += 1
    return rows, extra


# --- values ----------------------------------------------------------------------------

def same(kind, got, want):
    if kind == "Double":
        try:
            return abs(float(got) - float(want)) <= 1e-9 * max(1.0, abs(float(want)))
        except (TypeError, ValueError):
            return False
    return got == want


PROPERTY_FIELDS = {"Id": ("m_id", "id"), "LevelId": ("m_assocLevelId", "id"), "CreatedPhaseId": ("m_createdPhaseId", "id"),
                   "DemolishedPhaseId": ("m_demolishedPhaseId", "id"), "OwnerViewId": ("m_ownerDBViewId", "id"),
                   "Name": ("m_name", None), "Pinned": ("m_locked", None)}


# Properties the API computes from the live session, not from the file.
RUNTIME_PROPERTIES = {"IsValidObject", "IsTransient", "IsModifiable", "CanBeDeleted", "CanBeRenamed", "CanBeCopied"}


def compare_values(api, facts, enum_ids):
    by_id = {}
    for e in facts["elements"]:
        by_id.setdefault(e["id"], e)
    # Project, shared and family parameters are stored under their parameter element's id; several
    # elements may share a name (each family its own Width), so every one of the name is tried.
    pe_ids = collections.defaultdict(set)
    for a in api:
        if a["class"].endswith(("ParameterElement", "SharedParameterElement", "GlobalParameter")):
            pe_ids[a["name"]].add(a["id"])
    header_params = {h["id"]: h.get("header_params") or [] for h in facts.get("headers", [])}
    partition = {r[1]: int.from_bytes(bytes.fromhex(r[5])[36:40], "little")
                 for r in facts["elem_table"] if len(r) > 5 and r[4] == 40}
    rows, c = [], collections.Counter()
    for a in api:
        e = by_id.get(a["id"])
        stored, derived = {}, {}
        if e:
            for pid, (kind, v) in e["params"]:
                stored.setdefault(pid, (kind, v))
            # Values Revit shows from a field: the element header's, then the element object's.
            for src, plist in (("the element header", header_params.get(a["id"], [])), ("an element field", e.get("field_params", []))):
                for pid, (kind, v) in plist:
                    derived.setdefault(pid, (src, kind, v))
        for p in a["parameters"]:
            if not p.get("has_value"):
                c["parameter without a value (nothing to decode)"] += 1
                continue
            if p.get("builtin") not in (None, "", "INVALID"):
                pid = enum_ids.get(p["builtin"])
            else:
                ids = pe_ids.get(p["name"], set())
                pid = next((i for i in sorted(ids) if i in stored), min(ids) if ids else None)
            if pid is None:
                st = "parameter id not known"
            elif pid not in stored and pid in derived:
                src, kind, v = derived[pid]
                st = ("match from " if kind == p["storage"] and same(kind, v, p["value"]) else "differ from ") + src
            elif pid not in stored:
                st = "not stored (computed?)" if p.get("read_only") else "not stored, writable"
            else:
                kind, v = stored[pid]
                if kind != p["storage"]:
                    st = "storage differs"
                elif same(kind, v, p["value"]):
                    st = "match"
                else:
                    st = "differ"
            c["parameter: " + st] += 1
            rows.append((a["id"], "parameter", p.get("builtin") or p["name"], p["storage"], st))
        for k, v in (a.get("properties") or {}).items():
            want = v.get("element_id") if isinstance(v, dict) and "element_id" in v else v
            if k in RUNTIME_PROPERTIES:
                st = "API runtime state (not file data)"
            elif k == "UniqueId":
                got = facts.get("unique_ids", {}).get(str(a["id"]))
                st = "not decoded" if got is None else ("match" if got == want else "differ")
            elif k == "WorksetId" and isinstance(v, dict):
                got = partition.get(a["id"])
                st = "not decoded" if got is None else ("match" if str(got) == v.get("text") else "differ")
            elif k == "DesignOption" and e and want is None:
                got = fid(e["root"], "m_designOptionId")
                st = "not decoded" if got is None else ("match" if got in (-1, -4) else "differ")
            elif k == "ViewSpecific" and e:
                got = fid(e["root"], "m_ownerDBViewId")
                st = "not decoded" if got is None else ("match" if (got != -1) == want else "differ")
            elif isinstance(want, dict):
                st = "object value (not compared)"
            elif k in PROPERTY_FIELDS and e:
                fname, sub = PROPERTY_FIELDS[k]
                got = field(e["root"], fname)
                got = got.get(sub) if sub and isinstance(got, dict) else got
                st = "not decoded" if got is None else ("match" if got == want else "differ")
            else:
                st = "no file field known"
            c["property: " + st] += 1
            rows.append((a["id"], "property", k, type(want).__name__, st))
    return rows, c


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("rvt")
    ap.add_argument("api_dump")
    ap.add_argument("facts")
    ap.add_argument("out")
    ap.add_argument("--floor")
    ap.add_argument("--write-floor")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    facts = json.load(open(a.facts))
    api = json.load(open(a.api_dump))["elements"]
    cls = {int(k): v for k, v in facts["classes"].items()}
    enum_ids = {k: v for k, v in facts.get("builtin_ids", {}).items()}

    led = Ledger()
    raw, file_len = cfb(a.rvt, led)
    inflated, parts = streams(led, raw)
    inflated_bytes(led, inflated, facts)
    sections = section_of(facts, parts)
    erows, extra = compare_elements(api, facts, sections, cls)
    vrows, vcount = compare_values(api, facts, enum_ids)

    with open(os.path.join(a.out, "bytes.tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(("domain", "stream", "start", "end", "class", "what"))
        w.writerows(sorted(led.rows))
    with open(os.path.join(a.out, "elements.tsv"), "w", newline="") as f:
        cols = ("id", "api_class", "file_class", "located") + ATTRS
        w = csv.DictWriter(f, cols, delimiter="\t", lineterminator="\n", restval="")
        w.writeheader()
        w.writerows(erows)
    with open(os.path.join(a.out, "values.tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(("id", "kind", "name", "storage", "status"))
        w.writerows(vrows)

    # Totals: (metric, value, better) with better "higher" or "lower".
    tot = []
    stored_streams = sum(len(b) for b in raw.values())
    file_classified = sum(e - s for d, _, s, e, c, _ in led.rows if d == "file")
    for dom in ("file", "stored", "inflated"):
        for c in ("decoded", "known", "unknown"):
            tot.append((f"bytes {dom} {c}", led.total(dom, c), "lower" if c != "decoded" else "higher"))
    tot.append(("bytes file total", file_len, "info"))
    tot.append(("bytes stored streams total", stored_streams, "info"))
    tot.append(("api elements", len(api), "info"))
    tot.append(("elements located", sum(r["located"] == "yes" for r in erows), "higher"))
    for k in ATTRS:
        for st in ("match", "differ", "not decoded"):
            n = sum(r.get(k) == st for r in erows)
            tot.append((f"attr {k} {st}", n, {"match": "higher", "differ": "lower", "not decoded": "lower"}[st]))
    for k, n in sorted(extra.items()):
        tot.append((f"file elements not in api: {k}", n, "info"))
    for k, n in sorted(vcount.items()):
        better = "higher" if (k.endswith(": match") or ": match from" in k) else ("info" if "without a value" in k else "lower")
        tot.append((f"values {k}", n, better))
    with open(os.path.join(a.out, "full-decode.tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(("metric", "value", "better"))
        w.writerows(tot)
    if a.write_floor:
        with open(a.write_floor, "w", newline="") as f:
            f.write("# Floor of tools/full-decode/full_decode.py on the tiny model 1-hip-roof (Revit 2024). "
                    "A run fails when a 'higher' metric drops below or a 'lower' metric rises above its value here.\n")
            w = csv.writer(f, delimiter="\t", lineterminator="\n")
            w.writerow(("metric", "value", "better"))
            w.writerows(t for t in tot if t[2] != "info")

    md = ["## Full decode: 1-hip-roof (Revit 2024)", "",
          f"File {file_len:,} bytes; streams {stored_streams:,} bytes stored. API elements {len(api):,}.", "",
          "| Bytes | decoded | known, not decoded | unknown |", "|---|---|---|---|"]
    for dom, label in (("file", "file (container, stream sectors counted below)"), ("stored", "streams as stored"), ("inflated", "inflated streams")):
        md.append(f"| {label} | {led.total(dom, 'decoded'):,} | {led.total(dom, 'known'):,} | {led.total(dom, 'unknown'):,} |")
    md += ["", f"Elements located (element object with its ElementId and an element table row): "
           f"{sum(r['located'] == 'yes' for r in erows):,} of {len(api):,}.", "",
           "| Attribute | match | differ | not decoded |", "|---|---|---|---|"]
    for k in ATTRS:
        md.append(f"| {k} | " + " | ".join(f"{sum(r.get(k) == st for r in erows):,}" for st in ("match", "differ", "not decoded")) + " |")
    md += ["", "File element objects that are not API elements: " + "; ".join(f"{k} {n:,}" for k, n in sorted(extra.items())), "",
           "| Values | count |", "|---|---|"]
    md += [f"| {k} | {n:,} |" for k, n in sorted(vcount.items())]
    text = "\n".join(md) + "\n"
    open(os.path.join(a.out, "full-decode.md"), "w").write(text)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        open(os.environ["GITHUB_STEP_SUMMARY"], "a").write(text)
    print(text)

    if a.floor:
        floor = {}
        for row in csv.reader((l for l in open(a.floor) if not l.startswith("#")), delimiter="\t"):
            if row and row[0] != "metric":
                floor[row[0]] = (int(row[1]), row[2])
        got = {m: v for m, v, _ in tot}
        bad = []
        for m, (v, better) in floor.items():
            g = got.get(m, 0)
            if (better == "higher" and g < v) or (better == "lower" and g > v):
                bad.append(f"{m}: {g} (floor {v}, {better} is better)")
        if bad:
            print("Coverage fell below the floor:\n  " + "\n  ".join(bad))
            return 1
        print(f"Floor held ({len(floor)} metrics).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
