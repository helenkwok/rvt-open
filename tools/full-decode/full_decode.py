#!/usr/bin/env python3
"""How completely rvt-open decodes one Revit file, on three axes, against its Revit API dump.

Inputs: the `.rvt`, its `<recipe>.api-dump.json` (every element the Revit API returns,
with its parameters and properties) and the facts rvt-open's schema reader writes about
the file (`cargo run --example full_decode -- model.rvt > facts.json`).

1. Bytes. Every byte of the file is classified `decoded` (its meaning is read and checked:
   container structures, page parity recomputed, gzip members inflated with their CRC,
   partition framing whose sizes agree, object fields read by the schema), `known` (the
   structure around it is known, its content is not read: e.g. a signature value, an
   object graph the reader does not account byte by byte) or `unknown`. Counted in the
   stored file and, for compressed streams, in their inflated bytes.
2. Elements. Every API element must be an element object of the file (root `m_id` equal to
   its ElementId) with a row in `Global/ElemTable`; each attribute (class, category,
   is_type, name, level, host, workset, phases, design option, unique_id) is `match`,
   `differ` or `not decoded`. Every element object of the file must be an API element or
   be explained (the elements of embedded content documents, after the partition's first
   section header).
3. Values. Every parameter value the API reports is looked up among the element's stored
   parameters (by built-in id, or by the parameter element's id) and compared by storage
   type and value (lengths in internal feet, as stored); a value the file does not store
   is `not stored`. Properties are compared where a file field is known for them.

Writes OUT/bytes.tsv, OUT/elements.tsv, OUT/values.tsv, OUT/full-decode.tsv (the totals)
and OUT/full-decode.md (also to $GITHUB_STEP_SUMMARY). With --floor TSV, exits 1 when a
total is worse than the floor's (a count of decoded or matched things fell, or a count of
unknown or differing things rose). --write-floor TSV writes the measured totals.

Usage: full_decode.py RVT API_DUMP FACTS OUT [--floor TSV | --write-floor TSV]
"""
