PAGE, TRAILER = 65249, 353
# Page code of a stream's pages (every page, full or short): an interleaved CRC whose
# (u, d) follow from the page length; polynomials MSB first.
POLY = {3: 0b1011, 4: 0b10011, 5: 0b100101, 6: 0b1000011, 7: 0b10000011, 9: 0b1000010001, 11: 0b100000000101}
GZIP_HEAD = b"\x1f\x8b\x08"
SECTION_TEXT = "Data generated by ".encode("utf-16-le")
FREESECT, ENDOFCHAIN, FATSECT, DIFSECT = 0xFFFFFFFF, 0xFFFFFFFE, 0xFFFFFFFD, 0xFFFFFFFC


def page_code(n):
    """(u, d, rows) of a page of n bytes: the smallest d*u with 65 <= u <= 255 and 8n mod u <= 7."""
    bits, best = 8 * n, None
    for u in range(65, 256):
        if bits % u > 7:
            continue
        d = next((d for d in (3, 4, 5, 6, 7, 9, 11) if 2**d - 1 >= bits // u), None)
        if d is not None and (best is None or d * u < best[0] * best[1]):
            best = (d, u)
    if best is None:
        return None
    d, u = best
    return u, d, bits // u


def page_ok(page):
    """True when every codeword of `page` checks and its pad bits are zero."""
    code = page_code(len(page))
    if code is None:
        return False
    u, d, rows = code
    v, mask, poly = int.from_bytes(page, "little"), (1 << u) - 1, POLY[d]
    reg = [0] * d  # bit plane k of every codeword's CRC register
    for r in range(rows - d):
        top = reg[d - 1] ^ ((v >> (r * u)) & mask)
        reg = [0] + reg[:-1]
        for k in range(d):
            if (poly >> k) & 1:
                reg[k] ^= top
    for i, r in enumerate(range(rows - d, rows)):
        if reg[d - 1 - i] != (v >> (r * u)) & mask:
            return False
    return v >> (u * rows) == 0


class Ledger:
    """Byte ranges by (domain, stream, class, what)."""

    def __init__(self):
        self.rows = []

    def add(self, domain, stream, start, end, cls, what):
        if end > start:
            self.rows.append((domain, stream, start, end, cls, what))

    def total(self, domain, cls):
        return sum(e - s for d, _, s, e, c, _ in self.rows if d == domain and c == cls)


def cfb(path, led):
    """Classify the container: header, FAT, DIFAT, directory, mini FAT, mini stream, slack, free sectors."""
    o = olefile.OleFileIO(path)
    data = open(path, "rb").read()
    ss = o.sectorsize
    led.add("file", "(container)", 0, 512, "decoded", "CFB header")
    if len(data) > 512:
        led.add("file", "(container)", 512, ss, "decoded" if not any(data[512:ss]) else "unknown", "header sector padding")
    owner = {}

    def chain(start):
        out, s = [], start
        while s not in (ENDOFCHAIN, FREESECT) and s < len(o.fat) and len(out) <= len(o.fat):
            out.append(s)
            s = o.fat[s]
        return out

    for i, v in enumerate(o.fat[: o.nb_sect]):
        if v == FATSECT:
            owner[i] = ("FAT", None)
        elif v == DIFSECT:
            owner[i] = ("DIFAT", None)
    for s in chain(o.first_dir_sector):
        owner[s] = ("directory", None)
    if o.first_mini_fat_sector not in (ENDOFCHAIN, FREESECT):
        for s in chain(o.first_mini_fat_sector):
            owner[s] = ("mini FAT", None)
    for s in chain(o.root.isectStart):
        owner[s] = ("mini stream", None)
    names = {}
    for parts in o.listdir():
        e = o.direntries[o._find(parts)]
        names[id(e)] = "/".join(parts)
        if e.size >= o.minisectorcutoff:
            for s in chain(e.isectStart):
                owner[s] = ("stream", e)
    for s in range(o.nb_sect):
        at = 512 + s * ss
        sect = data[at : at + ss]
        kind, e = owner.get(s, ("free", None))
        if kind == "stream":
            led.add("file", names[id(e)], at, at + ss, "stream", "stream sector")
        elif kind == "free":
            led.add("file", "(container)", at, at + len(sect), "decoded" if not any(sect) else "unknown", "free sector")
        elif kind == "directory":
            for k in range(0, len(sect), 128):
                ent = sect[k : k + 128]
                used = ent[66] != 0
                # An unused entry (type 0) names nothing; Revit leaves stale bytes in some.
                clean = used or not any(ent[:64] + ent[66:])
                led.add("file", "(container)", at + k, at + k + len(ent), "decoded" if clean else "known",
                        "directory entry" if used else ("unused directory entry" if clean else "unused directory entry: stale bytes"))
        elif kind == "mini stream":
            led.add("file", "(mini stream)", at, at + len(sect), "stream", "mini stream sector")
        else:
            led.add("file", "(container)", at, at + len(sect), "decoded", kind + " sector")
    # Stream sectors: the stream's bytes, then slack to the sector's end.
    out = {}
    for parts in o.listdir():
        name = "/".join(parts)
        e = o.direntries[o._find(parts)]
        raw = o.openstream(name).read()
        out[name] = raw
        if e.size >= o.minisectorcutoff:
            secs = chain(e.isectStart)
            slack = len(secs) * ss - e.size
            last = 512 + secs[-1] * ss
            tail = data[last + ss - slack : last + ss] if slack else b""
            led.add("file", name, 0, slack, "decoded" if not any(tail) else "known",
                    "sector slack past the stream's end" + ("" if not any(tail) else ": stale bytes, part of no stream"))
    # Mini stream: each small stream's mini sectors, their slack, unused mini sectors.
    mini = o._open(o.root.isectStart, o.root.size).read() if o.root.size else b""
    used = set()
    for parts in o.listdir():
        e = o.direntries[o._find(parts)]
        if e.size >= o.minisectorcutoff:
            continue
        s, n = e.isectStart, 0
        while s not in (ENDOFCHAIN, FREESECT) and s < len(o.minifat):
            used.add(s)
            n += 1
            s = o.minifat[s]
        slack = n * 64 - e.size
        last = None
        s = e.isectStart
        while s not in (ENDOFCHAIN, FREESECT) and s < len(o.minifat):
            last = s
            s = o.minifat[s]
        tail = mini[last * 64 + 64 - slack : last * 64 + 64] if last is not None and slack else b""
        led.add("file", "/".join(parts), 0, slack, "decoded" if not any(tail) else "known",
                "mini sector slack" + ("" if not any(tail) else ": stale bytes, part of no stream"))
    for k in range(len(mini) // 64):
        if k not in used:
            blk = mini[k * 64 : k * 64 + 64]
            led.add("file", "(mini stream)", k * 64, k * 64 + 64, "decoded" if not any(blk) else "unknown", "unused mini sector")
    led.add("file", "(mini stream)", 0, max(0, o.root.size - (len(mini) // 64) * 64), "decoded", "mini stream tail")
    # The mini stream's own sector slack.
    if o.root.size:
        secs = chain(o.root.isectStart)
        slack = len(secs) * ss - o.root.size
        last = 512 + secs[-1] * ss
        tail = data[last + ss - slack : last + ss]
        led.add("file", "(mini stream)", 0, slack, "decoded" if not any(tail) else "known",
                "mini stream sector slack" + ("" if not any(tail) else ": stale bytes, part of no stream"))
    o.close()
    return out, len(data)


def coded_pages(raw):
    """Split a stream into its data bytes and its parity bytes, page by page. Returns
    (data, parity byte count, pages failing their code)."""
    data, parity, bad = bytearray(), 0, 0
    for at in range(0, len(raw), PAGE):
        page = raw[at : at + PAGE]
        if not page_ok(page):
            bad += 1
        if len(page) == PAGE:
            data += page[: PAGE - TRAILER]
            parity += TRAILER
        else:
            u, d, rows = page_code(len(page))
            cap = (rows - d) * u // 8
            data += page[:cap]
            parity += len(page) - cap
    return bytes(data), parity, bad


def members(buf, start):
    """Gzip members of `buf` from `start`, back to back or separated: [(offset, end, inflated)]."""
    out, at = [], start
    while True:
        j = buf.find(GZIP_HEAD, at)
        if j < 0:
            return out
        z = zlib.decompressobj(31)
        try:
            body = z.decompress(buf[j:])
        except zlib.error:
            at = j + 1
            continue
        if not z.eof:
            at = j + 1
            continue
        end = len(buf) - len(z.unused_data)
        out.append((j, end, body))
        at = end


def zero_or(buf, cls="unknown"):
    return "decoded" if not any(buf) else cls


def tail_zeros(led, name, data, end):
    """From `end` to the page data's end: zeros, then the stream's end bits (non-zero bits in the
    last data byte before the page parity, which the page code covers; their meaning is not known)."""
    last = len(data) - 1 if len(data) > end and data[-1] else len(data)
    led.add("stored", name, end, last, zero_or(data[end:last]), "zeros after the data")
    led.add("stored", name, last, len(data), "known", "end bits before the page parity")


def single_member(led, name, data, first):
    """`Formats/Latest`, `Global/*`, `Contents`: a head, one gzip member, zeros to the page data's end."""
    ms = members(data, first)
    if not ms or ms[0][0] != first:
        led.add("stored", name, 0, len(data), "unknown", "no gzip member where expected")
        return None
    j, end, body = ms[0]
    led.add("stored", name, j, end, "decoded", "gzip member (CRC-32 and length checked)")
    tail_zeros(led, name, data, end)
    return body


def partition(led, name, data):
    """A partition: u64 version, then sections of segments, each a marker, a channel, a gzip member,
    a checkback; a 220-byte header between sections; a terminal. Returns (members, section of each)."""
    ms = members(data, 0)
    if not ms:
        led.add("stored", name, 0, len(data), "unknown", "no gzip member")
        return [], []
    sections, section, prev_end = [], 0, 0
    for k, (j, end, body) in enumerate(ms):
        head = data[prev_end:j]
        # The segment marker ends 8 bytes (the channel) before the member: u16 tag, u32
        # continuation, u32 objects, u32 stored length + 8, u32 payload bytes.
        stored_len = struct.unpack_from("<I", head, len(head) - 16)[0] if len(head) >= 26 else -1
        marker_ok = stored_len == end - j + 8
        if k == 0:
            led.add("stored", name, 0, 8, "decoded", "partition format version")
            led.add("stored", name, 8, j, "decoded" if marker_ok and j - 8 == 36 else "unknown", "content marker, segment marker, channel")
        elif SECTION_TEXT in head:
            section += 1
            t = head.find(SECTION_TEXT)
            sig = t - 4 - 64  # SignatureMarker value: the 64 bytes before u32 34 and the text
            led.add("stored", name, prev_end, prev_end + sig, "decoded" if marker_ok else "unknown", "checkback, zero marker, signature marker head")
            led.add("stored", name, prev_end + sig, prev_end + sig + 64, "known", "section signature value (64 bytes, meaning not known)")
            led.add("stored", name, prev_end + sig + 64, j, "decoded" if marker_ok else "unknown", "section text, content marker, section key, segment marker, channel")
        else:
            led.add("stored", name, prev_end, j, "decoded" if marker_ok and len(head) == 32 else "unknown", "checkback, segment marker, channel")
        led.add("stored", name, j, end, "decoded", "gzip member (CRC-32 and length checked)")
        sections.append(section)
        prev_end = end
    rest = data[prev_end:]
    t = rest.find(SECTION_TEXT)
    if t >= 0:
        sig = t - 4 - 64
        # u32 character count, the UTF-16 text, then a content marker (u16 tag, u32 0, i32 -1).
        term = t + 2 * struct.unpack_from("<I", rest, t - 4)[0] + 10
        led.add("stored", name, prev_end, prev_end + sig, "decoded", "terminal: checkback, zero marker, signature marker head")
        led.add("stored", name, prev_end + sig, prev_end + sig + 64, "known", "terminal signature value (64 bytes, meaning not known)")
        led.add("stored", name, prev_end + sig + 64, prev_end + term, "decoded", "terminal text and content marker")
        tail_zeros(led, name, data, prev_end + term)
    else:
        led.add("stored", name, prev_end, len(data), "unknown", "after the last member")
    return ms, sections


def streams(led, raw):
    """Every stream's stored bytes. Returns {name: inflated bytes} and partition member maps."""
    inflated, parts = {}, {}
    for name, b in sorted(raw.items()):
        coded = name.startswith(("Formats/", "Global/", "Partitions/")) or name == "Contents"
        if coded:
            data, parity, bad = coded_pages(b)
            led.add("stored", name, len(data), len(data) + parity, "decoded" if not bad else "unknown",
                    "page parity (every codeword recomputed)" if not bad else "page parity that does not check")
        else:
            data = b
        if name == "Formats/Latest":
            inflated[name] = single_member(led, name, data, 0)
        elif name.startswith("Global/"):
            led.add("stored", name, 0, 4, "known", "stream prefix word (meaning not known)")
            led.add("stored", name, 4, 8, zero_or(data[4:8]), "stream prefix zero word")
            inflated[name] = single_member(led, name, data, 8)
        elif name == "Contents":
            ms = members(data, 0)
            first = ms[0][0] if ms else len(data)
            led.add("stored", name, 0, first, "known", "Contents header (release words; rest not read)")
            inflated[name] = single_member(led, name, data, first) if ms else None
        elif name.startswith("Partitions/"):
            parts[name] = partition(led, name, data)
            inflated[name] = b"".join(m[2] for m in parts[name][0])
        else:
            led.add("stored", name, 0, len(b), "known", "read by rvt-open, not accounted byte by byte")
    return inflated, parts


def inflated_bytes(led, inflated, facts):
    """The inflated bytes: partition objects through the schema reader; the element table's rows."""
    objs = collections.defaultdict(list)
    for o in facts["objects"]:
        objs[o["stream"]].append(o)
    heads = collections.defaultdict(list)
    for o in facts.get("headers", []):
        heads[o["stream"]].append(o)
    for p in facts["partitions"]:
        name = p["stream"]
        if len(inflated.get(name) or b"") != p["inflated"]:
            led.add("inflated", name, 0, p["inflated"], "unknown", "inflated length differs from the reader's")
            continue
        for o in objs[name]:
            s, e = o["span"]
            ps, pe = o["payload"]
            led.add("inflated", name, s, ps, "decoded", "object header (id, Adler-32, size)")
            un = o["unparsed"]
            if un:
                led.add("inflated", name, ps, un[0], "decoded", "object fields read by the schema")
                led.add("inflated", name, un[0], un[1], "known", "object bytes not read: " + (o["stopped"] or ""))
            else:
                led.add("inflated", name, ps, pe, "decoded", "object fields read by the schema")
            led.add("inflated", name, pe, e, "decoded", "object trailing size")
        if "header_markers" not in p:
            for s, e in p["gaps"]:
                led.add("inflated", name, s, e, "unknown", "between objects")
            continue
        for o in heads[name]:
            s, e = o["span"]
            ps, pe = o["payload"]
            led.add("inflated", name, s, ps, "decoded", "element-header record head (id, size)")
            un = o["unparsed"]
            if un:
                led.add("inflated", name, ps, un[0], "decoded", "element-header fields read by the schema")
                led.add("inflated", name, un[0], un[1], "known", "element-header bytes not read: " + (o["stopped"] or ""))
            else:
                led.add("inflated", name, ps, pe, "decoded", "element-header fields read by the schema")
            led.add("inflated", name, pe, e, "decoded", "element-header record trailing size")
        for s, e in p["header_markers"]:
            led.add("inflated", name, s, e, "decoded", "element-header run marker")
        for s, e in p["header_rest"]:
            led.add("inflated", name, s, e, "unknown", "between objects, not a header record")
    graphs = {g["stream"]: g for g in facts.get("graphs", [])}
    for name, b in sorted(inflated.items()):
        if b is None or name.startswith("Partitions/"):
            continue
        sch = facts.get("schema")
        if name == "Formats/Latest" and sch and sch["inflated"] == len(b):
            # Totals only: the GUID lists lie inside the class records, counted here at the end.
            # Each class record ends with a u32 GUID count (read) and that many GUIDs (stepped over).
            n, guids = sch["parsed"], sch["guid_list_bytes"] - 4 * sch["classes"]
            led.add("inflated", name, 0, n - guids, "decoded", "schema classes and fields read by the grammar (GUIDs counted apart)")
            led.add("inflated", name, n - guids, n, "known", "the classes' GUIDs, stepped over (total of all classes)")
            led.add("inflated", name, n, len(b), "unknown", "after the schema grammar stopped: " + (sch["stopped"] or ""))
            continue
        g = graphs.get(name)
        if g and "documents" in g and g["inflated"] == len(b):
            for d in g["documents"]:
                s, e = d["span"]
                gs, ge = d["graph"]
                led.add("inflated", name, s, d["key_read_to"], "decoded", "embedded document key read by the schema")
                led.add("inflated", name, d["key_read_to"], gs, "decoded", "embedded document size")
                led.add("inflated", name, gs, d["graph_read_to"], "decoded", "embedded document graph read by the schema")
                led.add("inflated", name, d["graph_read_to"], ge, "known", "embedded document bytes not read: " + (d["graph_stopped"] or ""))
                led.add("inflated", name, ge, e, "decoded", "embedded document trailing size")
            led.add("inflated", name, g["records_end"], len(b), "known", "closing key object (null pointer) and u32 0, not read")
            continue
        if not g or g.get("read_to", 0) == 0 or g["inflated"] != len(b):
            led.add("inflated", name, 0, len(b), "known", "not read as an object graph")
            continue
        r = g["read_to"]
        led.add("inflated", name, 0, r, "decoded", "object graph read by the schema")
        rest = b[r:]
        if rest == b"\0\0\0\0":
            led.add("inflated", name, r, len(b), "decoded", "u32 0 after the graph")
        elif name == "Global/History" and len(rest) >= 8 and len(rest) == 8 + 17 * struct.unpack_from("<I", rest)[0] \
                and rest[-4:] == b"\0\0\0\0":
            # u32 n, n episodes (16-byte GUID and one byte), u32 0: the episodes UniqueIds name.
            led.add("inflated", name, r, len(b), "decoded", "episode list and u32 0 after the graph")
        else:
            led.add("inflated", name, r, len(b), "known", "after the object graph: " + (g["stopped"] or ""))


